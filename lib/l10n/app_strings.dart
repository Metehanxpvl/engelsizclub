/// - `S.n('key', {'n': '3'})` yer tutuculu
/// - `S.auto('Türkçe metin')` seçilen dile otomatik çeviri (önbellekli)
abstract final class S {
  static String t(String key) {
    final lang = LocaleController.instance.lang;
    final table = _tables[lang] ?? _tables[AppLang.tr]!;
    return table[key] ?? _tables[AppLang.tr]![key] ?? key;
  }

  static String n(String key, Map<String, String> vars) {
    var s = t(key);
    vars.forEach((k, v) {
      s = s.replaceAll('{$k}', v);
    });
    return s;
  }

  /// Kaynak metin Türkçe kabul edilir; dil TR ise aynen döner.
  static String auto(String turkishSource, {String from = 'tr'}) {
    if (LocaleController.instance.lang == AppLang.tr) return turkishSource;
    return ContentTranslator.instance.sync(turkishSource, from: from);
  }
